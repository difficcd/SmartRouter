# ---- features: prompt text -> fixed-length numeric vector ----------------
# Dense hand-picked counts/ratios + hashed word unigram/bigram counts
# (FNV-1a, signed -- no vocabulary/dictionary is stored, so no prompt text
# ever ends up in the artifact below).

_TEAM_FNV_OFFSET_BASIS = 0xCBF29CE484222325
_TEAM_FNV_PRIME = 0x100000001B3
# _TEAM_FNV_PRIME) 알고리즘의 지정된 거대한 '특수한 소수(Prime Number)'
# 고정 상수 (64bit FNV-1a 해시 고정 상수.)
_TEAM_MASK_64 = (1 << 64) - 1  
# 64bit 마스크

_TEAM_WORD = re.compile(r"[0-9A-Za-z가-힣]+")
_TEAM_DENSE_FEATURE_NAMES: _TeamTuple[str, ...] = (
    "character_count_log1p",
    "word_count_log1p",
    "sentence_count_log1p",
    "message_count",
    "hangul_ratio",
    "code_marker_count",
    "math_marker_count",
    "numeric_density",
    "long_context",
    "reasoning_marker_count",
)


def _team_fnv1a64(data: bytes) -> int:
    value = _TEAM_FNV_OFFSET_BASIS
    for byte in data:
        value ^= byte   # XOR 
        value = (value * _TEAM_FNV_PRIME) & _TEAM_MASK_64
        # 마스킹 연산은 오버플로 방지용 
        
    return value
# 해시 함수 구현 (64bit 정수 : 16*4bit  해시값 반환)
# ref ) https://en.wikipedia.org/wiki/Fowler%E2%80%93Noll%E2%80%93Vo_hash_function 
# bytes : str을 직접 계산 불가. byte data로 바꿔야 계산 가능
# 순수한 이진 데이터(바이트 스트림) 으로 변환 : .encode() : hash_slot. 


def _team_hash_slot(token: str, hash_bins: int) -> _TeamTuple[int, float]:
    digest = _team_fnv1a64(token.encode("utf-8")) # token => 64bit hash value

    index = digest % hash_bins                   # 해시값을 해시칸개수로 modulo연산
    sign = 1.0 if (digest >> 63) & 1 else -1.0   # 최상위비트값이 1이면 +1.0 0이면 -1.0
                                                 # 충돌상쇄처리 (feature hashing) 
    return index, sign
# 해시 함수 구현 (해시 슬롯 매핑)




def _team_tokens(text: str) -> _TeamTuple[str, ...]:
    return tuple(match.group(0).lower() for match in _TEAM_WORD.finditer(text))
# 미리 정의된 정규식 패턴(_TEAM_WORD)을 이용해 단어들 뽑아내는 것.
# 자세한 이해는 반복학습
# (iterator => 단어 match단위로 통째로가져옴(group) => 튜플로 묶어 보냄)


def _team_bigrams(tokens: Sequence[str]) -> _TeamTuple[str, ...]:
    return tuple(f"{a} {b}" for a, b in zip(tokens, tokens[1:]))
# bigram 위한 튜플로 반환 (obsidian @STUDY 참조)



# 객체랑 객체내용을 한번에 받아서 "손으로 고른 10개 특징"을 만드는 함수
# heuristic 76-96행에 있던 extract_features 함수를 router 로직에 맞게 변형한 것.
def _team_dense_features(episode: Episode, text: str) -> _TeamTuple[float, ...]:    
    characters = len(text) 
    nonspace = sum(not ch.isspace() for ch in text) or 1
    hangul = sum("가" <= ch <= "힣" for ch in text)
    numbers = sum(ch.isdigit() for ch in text)
    words = _team_tokens(text)

    message_count = 1.0 if episode.prompt is not None else float(len(episode.messages or ()))
    sentence_count = max(1, len(_SENTENCE_END.findall(text)))
    # log1p = ln(1+x) 

    # 타입 정의를 하지 않는 이유 (dataclass 안쓰는이유):
    # 원본은 if분기(baseline)가 있어서 인자 이름을 아는 편이 보기쉬움.
    # 추가한 로직에서는 바로 list로 만들어버린 다음 
    return (
        _team_math.log1p(characters), # 텍스트 전체 글자수
        _team_math.log1p(len(words)), # 단어 목록 길이
        _team_math.log1p(sentence_count),  # 문장부호 개수
        # log1p : 너무 큰 영향력 가지는것 방지하기 위해 log처리해주는것.

        message_count,                     # prompt형이면 1.0, messages면 개수
        hangul / nonspace,                 # 한글 비율
        float(len(_CODE_MARKERS.findall(text))),    
        float(len(_MATH_MARKERS.findall(text))),    
        numbers / nonspace,                  # 숫자 비율
        1.0 if characters >= 8_000 else 0.0, # 8000자 넘으면 1.0 (flag)
        float(len(_REASONING_WORDS.findall(text))),
    )


# 문항 하나(Episode)를 받아서, 266개 숫자 튜플 하나로 바꿔서 뱉는 함수
# episode text 받아서 hash에 맞게 해싱하고, 고정특징+해싱으로 임베딩해서 Tuple 반환
def _team_raw_feature_vector(episode: Episode, hash_bins: int) -> _TeamTuple[float, ...]:
    # _TeamTuple[float, ...] )  float* (reg ex) 같은 느낌 (빈 튜플 허용, 반복 허용)

    text = episode_text(episode) 

    vector = list(_team_dense_features(episode, text))
    vector.extend(0.0 for _ in range(hash_bins))
    # 256개의 0.0을 뒤에 이어붙임. 
    # hash 랑 10개 임의 특성이랑 붙인거임.

    offset = len(_TEAM_DENSE_FEATURE_NAMES) # 고정특징 개수
    tokens = _team_tokens(text)             # 단어 뽑아내기

    for gram in (*tokens, *_team_bigrams(tokens)):
        index, sign = _team_hash_slot(gram, hash_bins)
        vector[offset + index] += sign
    # unigram 과 bigram 을 unpacking(*) 하여 펼쳐 꺼내고
    # gram이란 튜플단위로 hash 함수에 넣고 해싱하는 것. (sign:bias해소)
    # 유니그램별, 바이그램별 임베딩을 해서 합친 값을 0초기화된 칸에 넣어주는것.

    return tuple(vector) # read only, immutable (Tuple) 


