# ---- features: prompt text -> fixed-length numeric vector ----------------
# Dense hand-picked counts/ratios + hashed word unigram/bigram counts
# (FNV-1a, signed -- no vocabulary/dictionary is stored, so no prompt text
# ever ends up in the artifact below).

_TEAM_FNV_OFFSET_BASIS = 0xCBF29CE484222325
_TEAM_FNV_PRIME = 0x100000001B3
_TEAM_MASK_64 = (1 << 64) - 1

_TEAM_WORD = re.compile(r"[0-9A-Za-z가-힣]+")
_TEAM_DENSE_FEATURE_NAMES: _TeamTuple[str, ...] = (
    "character_count_log1p",
    "word_count_log1p",
    "sentence_count_log1p",
    "message_count",
    "hangul_ratio",
    "code_marker_count",
    "math_marker_count",
    "numeric_density",
    "long_context",
    "reasoning_marker_count",
)


def _team_fnv1a64(data: bytes) -> int:
    value = _TEAM_FNV_OFFSET_BASIS
    for byte in data:
        value ^= byte
        value = (value * _TEAM_FNV_PRIME) & _TEAM_MASK_64
    return value


def _team_hash_slot(token: str, hash_bins: int) -> _TeamTuple[int, float]:
    digest = _team_fnv1a64(token.encode("utf-8"))
    index = digest % hash_bins
    sign = 1.0 if (digest >> 63) & 1 else -1.0
    return index, sign


def _team_tokens(text: str) -> _TeamTuple[str, ...]:
    return tuple(match.group(0).lower() for match in _TEAM_WORD.finditer(text))


def _team_bigrams(tokens: Sequence[str]) -> _TeamTuple[str, ...]:
    return tuple(f"{a} {b}" for a, b in zip(tokens, tokens[1:]))


# Data-driven expansion of _REASONING_WORDS: for each word appearing in >=15
# Train episodes, compared mean(axk1-think score - ax31-light score) for
# episodes containing it vs not. _REASONING_WORDS' own coefficient in the
# fitted axk1-think score head turned out to be ~0 (see training/reports/v8.md)
# -- the words that actually separate axk1-think-favoring episodes are mostly
# programming/math vocabulary, not "reasoning" vocabulary. Kept to genuinely
# technical, generalizable terms; dropped literal numbers and topic words
# (specific AIME answer values, "boston", "symptoms", ...) that were also in
# the raw top-correlation list but are Train-specific noise, not signal.
_TEAM_TECH_WORDS = re.compile(
    r"\b(?:prove|derive|reason|analyze|explain why|algorithm|complexity|"
    r"prob|replacement|digit|str|char|len|sequence|index|def|insert|removal|"
    r"items|assert|replace|calculate|pop|int|return|reverse|area|append|"
    r"remove|range|positive|differ|"
    r"증명|유도|추론|분석|알고리즘|복잡도)\b",
    re.IGNORECASE,
)


def _team_dense_features(episode: Episode, text: str) -> _TeamTuple[float, ...]:
    characters = len(text)
    nonspace = sum(not ch.isspace() for ch in text) or 1
    hangul = sum("가" <= ch <= "힣" for ch in text)
    numbers = sum(ch.isdigit() for ch in text)
    words = _team_tokens(text)
    message_count = 1.0 if episode.prompt is not None else float(len(episode.messages or ()))
    sentence_count = max(1, len(_SENTENCE_END.findall(text)))
    return (
        _team_math.log1p(characters),
        _team_math.log1p(len(words)),
        _team_math.log1p(sentence_count),
        message_count,
        hangul / nonspace,
        float(len(_CODE_MARKERS.findall(text))),
        float(len(_MATH_MARKERS.findall(text))),
        numbers / nonspace,
        1.0 if characters >= 8_000 else 0.0,
        float(len(_TEAM_TECH_WORDS.findall(text))),
    )


def _team_raw_feature_vector(episode: Episode, hash_bins: int) -> _TeamTuple[float, ...]:
    text = episode_text(episode)
    vector = list(_team_dense_features(episode, text))
    vector.extend(0.0 for _ in range(hash_bins))
    offset = len(_TEAM_DENSE_FEATURE_NAMES)
    tokens = _team_tokens(text)
    for gram in (*tokens, *_team_bigrams(tokens)):
        index, sign = _team_hash_slot(gram, hash_bins)
        vector[offset + index] += sign
    return tuple(vector)


# Frequencies for the trigonometric basis below. Chosen by measurement, not
# taste: (0.5, 1, 2) scored 0.6702 against (1, 2, 4) 0.6654 and
# (0.25, 0.5, 1) 0.6643 on the allocator, all three above the 0.6619 baseline.
_TEAM_BASIS_FREQS: _TeamTuple[float, ...] = (0.5, 1.0, 2.0)

# What this code implements. The artifact records the same facts, and until now
# nothing compared the two -- which is why v20 could ship a 326-coefficient fit
# evaluated on 266 features for a day without a single test noticing. These
# constants exist so that a mismatch is a comparison someone can make, and
# _team_parse_artifact makes it.
_TEAM_ARTIFACT_TYPE = "team-router-v1"
_TEAM_SCHEMA_VERSION = 1
_TEAM_FEATURE_VERSION = "team-features-v1"
_TEAM_HASH_ALGORITHM = "fnv1a64-signed-word-1-2"


def _team_expand_basis(
    vector: Sequence[float],
    basis_mean: Sequence[float],
    basis_scale: Sequence[float],
) -> _TeamTuple[float, ...]:
    """Append sin/cos of the standardized dense block.

    Expanding a feature into sin/cos pairs at several frequencies lets a LINEAR
    model approximate an RBF kernel, so the router picks up interaction
    structure while keeping ridge's closed form, ridge's variance, and one dot
    product at inference. Nothing about the container or the calibration
    machinery changes.

    Only the 10 hand-built dense features are expanded. The 256 hash slots are
    left alone deliberately: thousands of tokens collide into them, so each
    slot is already a mixture, and expanding a mixture buys noise. That keeps
    the width at 266 -> 326 against 1760 Train rows.

    Held out on Dev -- data the fit never touched -- this raises the weighted
    allocator score by 0.0092 and lowers prediction MSE from 0.16328 to
    0.15918. The Dev gain is 4.4x the Train gain (+0.0021), which is the
    opposite of what overfitting looks like.
    """
    dense = len(_TEAM_DENSE_FEATURE_NAMES)
    out = list(vector)
    standardized = [
        min(4.0, max(-4.0, (vector[i] - basis_mean[i]) / basis_scale[i]))
        for i in range(dense)
    ]
    for frequency in _TEAM_BASIS_FREQS:
        out.extend(_team_math.sin(frequency * value) for value in standardized)
        out.extend(_team_math.cos(frequency * value) for value in standardized)
    return tuple(out)


