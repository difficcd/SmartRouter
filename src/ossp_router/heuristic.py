# ---- predict: q̂(x, m) and ĉ(x, m) for one episode -----------------------


def _team_linear(head: _TeamLinearHead, values: Sequence[float]) -> float:
    return head.intercept + _team_math.fsum(c * v for c, v in zip(head.coefficients, values))


def _team_predict_episode(
    episode: Episode, artifact: _TeamArtifact
) -> _TeamTuple[_TeamMapping[str, float], _TeamMapping[str, float]]:
    raw = _team_raw_feature_vector(episode, artifact.hash_bins)
    standardized = tuple(
        (v - m) / s for v, m, s in zip(raw, artifact.feature_mean, artifact.feature_scale)
    )
    scores = {
        m: min(1.0, max(0.0, _team_linear(artifact.score_heads[m], standardized)))
        for m in _TEAM_MODEL_IDS
    }
    def cost_from(heads, smear) -> _TeamMapping[str, float]:
        out = {
            m: _team_math.exp(
                min(50.0, max(-50.0, _team_linear(heads[m], standardized)))
            )
            * smear[m]
            for m in _TEAM_MODEL_IDS
        }
        light, mid, high = _TEAM_MODEL_IDS
        out[mid] = max(out[mid], out[light] * (1.0 + 1e-12))
        out[high] = max(out[high], out[mid] * (1.0 + 1e-12))
        return out

    # Two cost estimates, fit with different regularization for different
    # jobs -- see train_router.py: `costs` is the accurate-level one used for
    # the budget, `rank_costs` is the discriminative one used to compare
    # episodes against each other.
    costs = cost_from(artifact.log_cost_heads, artifact.cost_smear)
    rank_costs = cost_from(artifact.log_cost_rank_heads, artifact.cost_rank_smear)
    return scores, costs, rank_costs


# ---- allocate: batch-level λ-bisection with per-model risk multiplier ------


def _team_select_models(
    predicted_scores: Sequence[_TeamMapping[str, float]],
    predicted_costs: Sequence[_TeamMapping[str, float]],
    predicted_rank_costs: Sequence[_TeamMapping[str, float]],
    *,
    budget_multiplier: float,
    safety_ratio: float,
    risk_multiplier: _TeamMapping[str, float],
    high_cap_ratio: float = 1.0,
) -> _TeamTuple[str, ...]:
    # predicted_costs feeds the budget (cap, totals); predicted_rank_costs
    # feeds the EV comparison. Same quantity, two fits -- see train_router.py.
    light_total = _team_math.fsum(row[_TEAM_MODEL_IDS[0]] for row in predicted_costs)
    rank_light_total = _team_math.fsum(
        row[_TEAM_MODEL_IDS[0]] for row in predicted_rank_costs
    )
    # safety_ratio scales the ALLOWED EXCESS, not the whole multiplier.
    #
    # The old form (light_total * max(1.0, budget_multiplier * safety_ratio))
    # made safety_ratio mean wildly different things per tier: premium's 4.0x
    # budget at safety 0.7 still allowed 2.8x, but fast's 1.25x at safety 0.7
    # hit the max(1.0, ...) floor and allowed no promotion at all. Every
    # safety_ratio below 0.80 was the same dead value for fast, and 0.84 --
    # the value the search kept picking -- bought only 5% of the 25% it was
    # allowed to spend.
    #
    # Reading it as a fraction of the excess makes the parameter mean the same
    # thing everywhere ("spend this share of what the tier may spend beyond
    # all-light") and gives fast the same search resolution the other tiers
    # already had.
    cap = light_total * (1.0 + (budget_multiplier - 1.0) * safety_ratio)
    # risk_multiplier only discourages the most expensive model in proportion to
    # how much we (think we) trust its cost prediction -- if that prediction is
    # simply wrong (the exact hash_regex failure mode), no amount of discouraging
    # helps, because the premise it's reasoning from is broken. high_cap_ratio is
    # a hard backstop independent of prediction accuracy: no matter what the EV
    # comparison says, the most expensive model can never claim more than this
    # fraction of the tier's cap.
    high_model = _TEAM_MODEL_IDS[-1]
    high_cap = cap * high_cap_ratio

    def choose(penalty: float) -> _TeamTuple[_TeamTuple[str, ...], float, float]:
        selected = []
        for scores, rank_costs in zip(predicted_scores, predicted_rank_costs):
            model_id = max(
                _TEAM_MODEL_IDS,
                key=lambda candidate: (
                    scores[candidate]
                    - penalty
                    * risk_multiplier[candidate]
                    * rank_costs[candidate]
                    / rank_light_total,
                    -_TEAM_MODEL_IDS.index(candidate),
                ),
            )
            selected.append(model_id)
        total = _team_math.fsum(
            costs[model_id] for costs, model_id in zip(predicted_costs, selected)
        )
        high_total = _team_math.fsum(
            costs[model_id]
            for costs, model_id in zip(predicted_costs, selected)
            if model_id == high_model
        )
        return tuple(selected), total, high_total

    def violates(total: float, high_total: float) -> bool:
        return total > cap or high_total > high_cap

    selected, total, high_total = choose(0.0)
    if violates(total, high_total):
        low, high = 0.0, 1.0
        selected, total, high_total = choose(high)
        while violates(total, high_total) and high < 2.0**40:
            low, high = high, high * 2.0
            selected, total, high_total = choose(high)
        for _iteration in range(40):
            middle = (low + high) / 2.0
            candidate_selected, candidate_total, candidate_high_total = choose(middle)
            if not violates(candidate_total, candidate_high_total):
                high = middle
                selected, total, high_total = candidate_selected, candidate_total, candidate_high_total
            else:
                low = middle
    if violates(total, high_total):
        selected = tuple(_TEAM_MODEL_IDS[0] for _row in predicted_scores)

    return selected


# ---- router_main: the real entry point (container/entrypoint.py uses this) -


